// Copied from stylistics-backend@8165af5 (feedback load-author-profile and process-feedback
// schemas). Hub change: no user or database ids, since the document key identifies the document.
import { z } from 'zod'

/** Validates the public workflow input accepted by the feedback pipeline. */
export const feedbackWorkflowInputSchema = z.object({
  category: z.string().min(1),
  context: z.string().min(1),
  anchor: z.string().min(1),
  suggestedText: z.string().optional(),
  justification: z
    .string()
    .describe(
      'Original correction justification. Helps the agent distinguish normative issues from intentional stylistic choices.'
    ),
  action: z.enum(['accept', 'reject']),
  severity: z.enum(['high', 'medium', 'low']),
  suggestionType: z.enum(['track-change', 'comment-only']),
  comment: z.string().optional(),
  documentUuid: z
    .uuid()
    .describe(
      'Stable document identifier generated by the add-in. The workflow resolves the persisted document profile in the backend.'
    )
})

/** Validates the structured result returned by the document-feedback agent. */
export const processFeedbackResultSchema = z.object({
  status: z.enum(['updated', 'ignored']),
  decisionSummary: z.string().min(1),
  profileMarkdown: z.string().min(1).optional()
})

/** Prompt input accepted by the document-backed feedback prompt builder. */
export type ProcessFeedbackPromptInput = z.infer<typeof feedbackWorkflowInputSchema> & {
  authorProfile: string
}
